import test from "node:test";
import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { adminCookie, api, baseUrl, business, command, enabled } from "../helpers/agency-http";
import { testIdentity } from "../helpers/team-fixtures";

test("property form: furnishing, multi-photo creation/retry, 20-photo limit, featured image and keyboard/mobile gallery", { skip: !enabled, timeout: 180000 }, async () => {
  const cookie = await adminCookie();
  const state = await command(cookie, { action: "createClient", input: { name: "PHOTO VALIDATION OWNER", role: "OWNER",
    address: "TEST", identityReference: "PHOTO-OWNER-ID", nationality: "TEST", email: "", phone: "", propertyIds: [] } });
  const ownerId = state.clients.at(-1).id;
  const browser = await chromium.launch({ executablePath: process.env.PDF_CHROMIUM_PATH ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, hasTouch: true, reducedMotion: "reduce" });
    await context.addCookies([{ name: cookie.split("=")[0], value: cookie.slice(cookie.indexOf("=") + 1), url: `${baseUrl}/api/agency/`, httpOnly: true, sameSite: "Strict" }]);
    const page = await context.newPage(), errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(`${baseUrl}/fr/admin`); await page.locator(".business-tabs").waitFor();
    await page.locator(".business-tabs").getByRole("button", { name: "Biens", exact: true }).click();
    const form = page.locator(".new-property-form");
    const files = Array.from({ length: 21 }, (_, index) => ({ name: `property-${index + 1}.png`, mimeType: testIdentity.mime, buffer: Buffer.from(testIdentity.base64, "base64") }));
    await form.locator('input[name="photos"]').setInputFiles(files);
    await page.getByRole("alert").filter({ hasText: "Maximum 20 photos" }).waitFor();
    assert.equal(await form.locator(".property-editor-photos li").count(), 0);
    await form.locator('input[name="photos"]').setInputFiles([{ name: "invalid.pdf", mimeType: "application/pdf", buffer: Buffer.from("%PDF-TEST") }]);
    await page.getByRole("alert").filter({ hasText: "Choisissez des images JPEG/PNG" }).waitFor();
    await form.locator('input[name="photos"]').setInputFiles(files.slice(0, 3));
    await form.locator(".property-editor-photos li").filter({ hasText: "property-2.png" }).getByRole("button", { name: "Mettre en avant", exact: true }).click();
    assert.match(await form.locator(".property-editor-photos li").first().innerText(), /property-2.png[\s\S]*Photo principale/);
    for (const [name, value] of Object.entries({ title: "PHOTO FORM VALIDATION", address: "TEST ADDRESS", titleReference: "PHOTO-TITLE",
      price: "1000", area: "120", bedrooms: "2", rooms: "3", bathrooms: "1" })) await form.locator(`[name="${name}"]`).fill(value);
    await form.locator('[name="ownerId"]').selectOption(ownerId);
    await form.locator('[name="furnishing"]').selectOption("PARTIALLY_FURNISHED");
    let uploadCount = 0;
    await page.route("**/api/agency/media", async (route) => {
      if (route.request().method() === "POST" && route.request().postDataJSON().kind === "PHOTO" && ++uploadCount === 2) {
        await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { code: "TEST_UPLOAD_FAILURE", message: "UPLOAD FAILURE TEST" } }) });
      } else await route.continue();
    });
    await form.getByRole("button", { name: "Créer le bien en brouillon", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "Certaines photos n’ont pas pu être téléversées" }).waitFor();
    let persisted = await business(cookie);
    const property = persisted.properties.find((item: { title: string }) => item.title === "PHOTO FORM VALIDATION");
    assert.ok(property); assert.equal(property.furnishing, "PARTIALLY_FURNISHED");
    assert.equal(persisted.properties.filter((item: { title: string }) => item.title === property.title).length, 1);
    assert.equal(await form.locator(".property-editor-photos li").count(), 2);
    assert.equal(await form.getByRole("button", { name: "Créer le bien en brouillon", exact: true }).isDisabled(), true);
    await page.unroute("**/api/agency/media");
    await form.getByRole("button", { name: "Téléverser les photos sélectionnées", exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll(".new-property-form .property-editor-photos li").length === 0);
    await page.locator('.business-workspace[aria-busy="false"]').first().waitFor();
    let assets = (await (await api(`media?propertyId=${property.id}`, undefined, cookie)).json()).data;
    assert.equal(assets.length, 3); assert.equal(assets[0].name, "property-2.png");
    assert.equal((await business(cookie)).properties.find((item: { id: string }) => item.id === property.id).image, `/api/v1/media/${assets[0].id}`);
    assert.equal((await api(`media/${assets[0].id}?preview=1`)).status, 401);
    const preview = await api(`media/${assets[0].id}?preview=1`, undefined, cookie);
    assert.ok(preview.headers.get("content-disposition")?.startsWith("inline"));
    assert.equal(preview.headers.get("cache-control"), "no-store");
    const card = page.locator(".business-list > article").filter({ has: page.getByRole("heading", { name: property.title, exact: true }) });
    await card.locator("summary").click();
    const photoForm = card.locator(".agency-photo-form");
    await photoForm.locator('input[name="photos"]:enabled').waitFor();
    await card.locator(".property-photo-gallery button").nth(2).waitFor();
    await page.waitForFunction(() => Array.from(document.querySelectorAll<HTMLImageElement>(".business-list .property-gallery .property-detail-image"))
      .some((image) => image.complete && image.naturalWidth > 0));
    await photoForm.locator('input[name="photos"]').setInputFiles(files.slice(3, 21));
    await card.getByRole("alert").filter({ hasText: "Maximum 20 photos" }).waitFor();
    await photoForm.locator('input[name="photos"]').setInputFiles(files.slice(3, 20));
    await photoForm.getByRole("button", { name: "Téléverser les photos sélectionnées", exact: true }).click();
    await card.locator(".agency-photo-form[aria-busy=false]").waitFor();
    assets = (await (await api(`media?propertyId=${property.id}`, undefined, cookie)).json()).data;
    assert.equal(assets.length, 20);
    assert.equal(await photoForm.locator('input[name="photos"]').isDisabled(), true);
    const last = assets.at(-1), feature = card.locator("li").filter({ has: page.getByRole("link", { name: last.name, exact: true }) });
    const coverChange = page.waitForResponse((response) => response.url().endsWith(`/api/agency/media/${last.id}`) && response.request().method() === "PATCH");
    await feature.getByRole("button", { name: "Mettre en avant", exact: true }).click();
    assert.equal((await coverChange).status(), 200);
    await feature.getByText("Photo principale", { exact: false }).waitFor();
    assert.equal((await api(`media/${last.id}`, undefined)).status, 401);
    const unauthorizedFeature = await fetch(`${baseUrl}/api/agency/media/${last.id}`, { method: "PATCH", headers: { Origin: baseUrl } });
    assert.equal(unauthorizedFeature.status, 401);
    const overflow = await api("media", { propertyId: property.id, kind: "PHOTO", name: "overflow.png", mime: testIdentity.mime, base64: testIdentity.base64 }, cookie);
    assert.equal(overflow.status, 409);
    persisted = await command(cookie, { action: "publish", propertyId: property.id, published: true });
    assert.equal(persisted.properties.find((item: { id: string }) => item.id === property.id).image, `/api/v1/media/${last.id}`);
    const catalogue = (await (await fetch(`${baseUrl}/api/v1/catalogue`)).json()).data.find((item: { id: string }) => item.id === property.id);
    assert.equal(catalogue.furnishing, "PARTIALLY_FURNISHED");
    assert.equal(catalogue.images.length, 20); assert.equal(catalogue.images[0], `/api/v1/media/${last.id}`);
    const generic = (await (await fetch(`${baseUrl}/api/v1/properties/${property.id}?locale=fr`)).json()).data;
    assert.equal(generic.furnishing, "PARTIALLY_FURNISHED"); assert.equal("agencyDetails" in generic, false);
    const publicPage = await context.newPage(); publicPage.on("pageerror", (error) => errors.push(error.message));
    await publicPage.goto(`${baseUrl}/fr/properties/${property.id}`);
    const gallery = publicPage.locator(".property-gallery");
    await gallery.locator(".property-photo-gallery button").last().waitFor();
    assert.equal(await gallery.locator(".property-detail-image").getAttribute("src"), `/api/v1/media/${last.id}`);
    assert.equal(await gallery.getByRole("status").innerText(), "1 / 20");
    await gallery.getByRole("button", { name: "Photo suivante", exact: true }).click();
    assert.equal(await gallery.getByRole("status").innerText(), "2 / 20");
    await gallery.getByRole("button", { name: "Photo suivante", exact: true }).press("ArrowLeft");
    assert.equal(await gallery.getByRole("status").innerText(), "1 / 20");
    await gallery.getByRole("button", { name: "Photo précédente", exact: true }).click();
    assert.equal(await gallery.getByRole("status").innerText(), "20 / 20");
    await gallery.getByRole("button", { name: "Photo 5", exact: true }).click();
    assert.equal(await gallery.getByRole("status").innerText(), "5 / 20");
    await publicPage.setViewportSize({ width: 390, height: 844 });
    await gallery.locator(".property-gallery-main").scrollIntoViewIfNeeded();
    const bounds = await gallery.locator(".property-gallery-main").boundingBox(); assert.ok(bounds);
    const touchSession = await context.newCDPSession(publicPage);
    await touchSession.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: bounds.x + bounds.width * .8, y: bounds.y + bounds.height / 2 }] });
    await touchSession.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: bounds.x + bounds.width * .2, y: bounds.y + bounds.height / 2 }] });
    await touchSession.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await touchSession.detach();
    assert.equal(await gallery.getByRole("status").innerText(), "6 / 20");
    assert.ok(await gallery.evaluate((element) => element.getBoundingClientRect().right <= document.documentElement.clientWidth));
    await publicPage.getByText("Partiellement meublé", { exact: true }).waitFor();
    await page.reload(); await page.locator(".business-tabs").waitFor();
    await page.locator(".business-tabs").getByRole("button", { name: "Biens", exact: true }).click();
    const reloadedCard = page.locator(".business-list > article").filter({ has: page.getByRole("heading", { name: property.title, exact: true }) });
    await reloadedCard.locator("summary").click();
    const details = reloadedCard.locator("form").filter({ has: page.locator('textarea[name="description"]') });
    await details.locator('[name="furnishing"]').selectOption("FURNISHED");
    assert.deepEqual(await details.evaluate((element) => Array.from((element as HTMLFormElement).elements)
      .filter((control) => control instanceof HTMLInputElement || control instanceof HTMLTextAreaElement || control instanceof HTMLSelectElement)
      .filter((control) => !control.checkValidity()).map((control) => ({ name: control.name, message: control.validationMessage }))), []);
    const savedDetails = page.waitForResponse((response) => response.url().endsWith("/api/agency/admin") && response.request().method() === "POST"
      && response.request().postDataJSON().action === "propertyDetails");
    await details.getByRole("button", { name: "Enregistrer", exact: true }).click();
    const detailsResponse = await savedDetails;
    assert.equal(detailsResponse.status(), 200, await detailsResponse.text());
    await page.locator('.business-workspace[aria-busy="false"]').first().waitFor();
    assert.equal((await business(cookie)).properties.find((item: { id: string }) => item.id === property.id).furnishing, "FURNISHED");
    const removal = await fetch(`${baseUrl}/api/agency/media/${last.id}`, { method: "DELETE", headers: { Cookie: cookie, Origin: baseUrl } });
    assert.equal(removal.status, 200);
    const afterRemoval = (await (await fetch(`${baseUrl}/api/v1/catalogue`)).json()).data.find((item: { id: string }) => item.id === property.id);
    assert.equal(afterRemoval.images.length, 19); assert.notEqual(afterRemoval.image, `/api/v1/media/${last.id}`);
    assert.equal((await business(cookie)).properties.find((item: { id: string }) => item.id === property.id).image, afterRemoval.image);
    assert.deepEqual(errors, []);
    await command(cookie, { action: "publish", propertyId: property.id, published: false });
  } finally { await browser.close(); }
});
